package iso_bc01.Dominio;

public class Devolucion {
	private int id;
	private String fecha;
	private String observaciones;
	public Estudiante unnamed_Estudiante_;
	public Prestamo unnamed_Prestamo_;
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getFecha() {
		return fecha;
	}
	public void setFecha(String fecha) {
		this.fecha = fecha;
	}
	public String getObservaciones() {
		return observaciones;
	}
	public void setObservaciones(String observaciones) {
		this.observaciones = observaciones;
	}
	public Estudiante getUnnamed_Estudiante_() {
		return unnamed_Estudiante_;
	}
	public void setUnnamed_Estudiante_(Estudiante unnamed_Estudiante_) {
		this.unnamed_Estudiante_ = unnamed_Estudiante_;
	}
	public Prestamo getUnnamed_Prestamo_() {
		return unnamed_Prestamo_;
	}
	public void setUnnamed_Prestamo_(Prestamo unnamed_Prestamo_) {
		this.unnamed_Prestamo_ = unnamed_Prestamo_;
	}
}